`timescale 1ns/1ps

module FloatDiv_tb;

    reg  [31:0] A, B;
    wire [31:0] Q; // Fixed missing semicolon

    // Corrected module instantiation
    FloatDiv uut (
        .A(A), .B(B),
        .Q(Q)
    );

    // Task for applying inputs, waiting for combinational logic, and checking
    task check_div;
        input [31:0] valA;
        input [31:0] valB;
        input [31:0] expected_Q;
        begin
            A = valA;
            B = valB;
            #10; // Wait for combinational propagation
            
            if (Q !== expected_Q) begin
                $display("FAIL: %h / %h = %h | Expected: %h", valA, valB, Q, expected_Q);
            end else begin
                $display("PASS: %h / %h = %h", valA, valB, Q);
            end
        end
    endtask

    initial begin
        $display("Starting Extended FloatDiv Combinational Tests...\n");

        // ==========================================
        // 1. Zero divided by Normal Numbers
        // ==========================================
        check_div(32'h00000000, 32'h3f800000, 32'h00000000); //  0.0 /  1.0 =  0.0
        check_div(32'h80000000, 32'h3f800000, 32'h80000000); // -0.0 /  1.0 = -0.0
        check_div(32'h00000000, 32'hbf800000, 32'h80000000); //  0.0 / -1.0 = -0.0
        check_div(32'h80000000, 32'hbf800000, 32'h00000000); // -0.0 / -1.0 =  0.0

        // ==========================================
        // 2. Zero divided by Subnormal Numbers
        // ==========================================
        check_div(32'h00000000, 32'h00400000, 32'h00000000); //  0.0 /  2^-127 =  0.0
        check_div(32'h80000000, 32'h00400000, 32'h80000000); // -0.0 /  2^-127 = -0.0
        check_div(32'h00000000, 32'h80400000, 32'h80000000); //  0.0 / -2^-127 = -0.0
        check_div(32'h80000000, 32'h80400000, 32'h00000000); // -0.0 / -2^-127 =  0.0

        // ==========================================
        // 3. Normal / Normal (Positive Exact Values)
        // ==========================================
        check_div(32'h3f800000, 32'h3f800000, 32'h3f800000); //  1.0 /  1.0  =  1.0
        check_div(32'h40000000, 32'h40000000, 32'h3f800000); //  2.0 /  2.0  =  1.0
        check_div(32'h40800000, 32'h40000000, 32'h40000000); //  4.0 /  2.0  =  2.0
        check_div(32'h40000000, 32'h40800000, 32'h3f000000); //  2.0 /  4.0  =  0.5
        check_div(32'h41200000, 32'h40000000, 32'h40a00000); // 10.0 /  2.0  =  5.0
        check_div(32'h40a00000, 32'h40000000, 32'h40200000); //  5.0 /  2.0  =  2.5
        check_div(32'h40200000, 32'h40000000, 32'h3fa00000); //  2.5 /  2.0  =  1.25
        check_div(32'h40200000, 32'h3fa00000, 32'h40000000); //  2.5 / 1.25  =  2.0
        check_div(32'h40400000, 32'h3fc00000, 32'h40000000); //  3.0 /  1.5  =  2.0
        check_div(32'h3fc00000, 32'h3f000000, 32'h40400000); //  1.5 /  0.5  =  3.0
        check_div(32'h40c00000, 32'h40400000, 32'h40000000); //  6.0 /  3.0  =  2.0
        check_div(32'h41400000, 32'h40400000, 32'h40800000); // 12.0 /  3.0  =  4.0
        check_div(32'h41700000, 32'h40400000, 32'h40a00000); // 15.0 /  3.0  =  5.0
        check_div(32'h41880000, 32'h40000000, 32'h41080000); // 17.0 /  2.0  =  8.5
        check_div(32'h41080000, 32'h3f000000, 32'h41880000); //  8.5 /  0.5  = 17.0
        check_div(32'h3e800000, 32'h3f000000, 32'h3f000000); // 0.25 /  0.5  =  0.5

        // ==========================================
        // 4. Normal / Normal (Mixed Signs)
        // ==========================================
        check_div(32'hbf800000, 32'h3f800000, 32'hbf800000); // -1.0 /  1.0  = -1.0
        check_div(32'h3f800000, 32'hbf800000, 32'hbf800000); //  1.0 / -1.0  = -1.0
        check_div(32'hbf800000, 32'hbf800000, 32'h3f800000); // -1.0 / -1.0  =  1.0
        check_div(32'hc0800000, 32'hc0000000, 32'h40000000); // -4.0 / -2.0  =  2.0
        check_div(32'hc1200000, 32'h40000000, 32'hc0a00000); // -10.0/  2.0  = -5.0
        check_div(32'h41200000, 32'hc0000000, 32'hc0a00000); //  10.0/ -2.0  = -5.0
        check_div(32'h3e800000, 32'hbf000000, 32'hbf000000); //  0.25/ -0.5  = -0.5
        check_div(32'hbe800000, 32'hbf000000, 32'h3f000000); // -0.25/ -0.5  =  0.5
        check_div(32'hc1880000, 32'h41880000, 32'hbf800000); // -17.0/ 17.0  = -1.0
        check_div(32'hc0c00000, 32'hc0400000, 32'h40000000); // -6.0 / -3.0  =  2.0

        // ==========================================
        // 5. Normal / Normal -> Subnormal Result
        // ==========================================
        // 2^-126 is the smallest normal number (32'h00800000)
        check_div(32'h00800000, 32'h40000000, 32'h00400000); // 2^-126 / 2.0 = 2^-127
        check_div(32'h00800000, 32'h40800000, 32'h00200000); // 2^-126 / 4.0 = 2^-128
        check_div(32'h80800000, 32'h40000000, 32'h80400000); // -2^-126/ 2.0 = -2^-127
        check_div(32'h80800000, 32'hc0000000, 32'h00400000); // -2^-126/-2.0 = 2^-127

        // ==========================================
        // 6. Subnormal / Normal
        // ==========================================
        check_div(32'h00400000, 32'h40000000, 32'h00200000); // 2^-127 / 2.0 = 2^-128
        check_div(32'h00200000, 32'h40000000, 32'h00100000); // 2^-128 / 2.0 = 2^-129
        check_div(32'h00000004, 32'h40000000, 32'h00000002); // 2^-147 / 2.0 = 2^-148
        check_div(32'h00000002, 32'h40000000, 32'h00000001); // 2^-148 / 2.0 = 2^-149 (Smallest Subnormal)
        check_div(32'h80200000, 32'h40000000, 32'h80100000); // -2^-128/ 2.0 = -2^-129
        check_div(32'h00000002, 32'hc0000000, 32'h80000001); // 2^-148 /-2.0 = -2^-149

        // ==========================================
        // 7. Subnormal / Subnormal
        // ==========================================
        check_div(32'h00400000, 32'h00400000, 32'h3f800000); // 2^-127 / 2^-127 =  1.0
        check_div(32'h00400000, 32'h00200000, 32'h40000000); // 2^-127 / 2^-128 =  2.0
        check_div(32'h00200000, 32'h00400000, 32'h3f000000); // 2^-128 / 2^-127 =  0.5
        check_div(32'h00000004, 32'h00000002, 32'h40000000); // 2^-147 / 2^-148 =  2.0
        check_div(32'h00000002, 32'h00000004, 32'h3f000000); // 2^-148 / 2^-147 =  0.5
        check_div(32'h00000001, 32'h00000001, 32'h3f800000); // 2^-149 / 2^-149 =  1.0
        check_div(32'h80400000, 32'h00400000, 32'hbf800000); // -2^-127/ 2^-127 = -1.0
        check_div(32'h80000001, 32'h00000001, 32'hbf800000); // -2^-149/ 2^-149 = -1.0

        // ==========================================
        // 8. Normal / Subnormal -> Large Normal Result
        // ==========================================
        check_div(32'h3f800000, 32'h00400000, 32'h7f000000); //  1.0 / 2^-127 =  2^127
        check_div(32'h40000000, 32'h00800000, 32'h7f000000); //  2.0 / 2^-126 =  2^127
        
        $display("\nSimulation Complete.");
        $finish;
    end

endmodule